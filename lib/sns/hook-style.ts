// 모델이 금지 이모지·해시태그를 어겼을 때의 최후 방어선
export function scrubThreads(text: string): string {
  return text.replace(/[💥👀🔥😱]/gu, '').replace(/\s#[^\s#]+/g, '').replace(/[ \t]+\n/g, '\n').trim();
}
