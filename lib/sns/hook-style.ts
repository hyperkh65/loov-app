// 모델이 형식을 어겨도 한 덩어리로 안 나가게: 문장마다 줄바꿈, 첫 문장 뒤 빈 줄
export function formatHookLines(text: string): string {
  const t = text.trim();
  if (!t || t.split('\n').filter(l => l.trim()).length >= 3) return t;
  const parts = t.split(/(?<=[.!?。…]|[다요음임함듦])\s+/).map(s => s.trim()).filter(Boolean);
  if (parts.length < 2) return t;
  return [parts[0], '', ...parts.slice(1)].join('\n');
}

// 모델이 금지 이모지·해시태그를 어겼을 때의 최후 방어선 + 줄바꿈 보정
export function scrubThreads(text: string): string {
  return formatHookLines(text.replace(/[💥👀🔥😱]/gu, '').replace(/\s#[^\s#]+/g, '').replace(/[ \t]+\n/g, '\n').trim());
}
